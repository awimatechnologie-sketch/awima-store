// لا مكتبات خارجية. يُستعمل في القوالب (.astro) وفي سكربتات المتصفح وفي الاختبارات.
export type Lang = 'ar' | 'fr';
export const LANGS: Lang[] = ['ar', 'fr'];
export const DEFAULT_LANG: Lang = 'ar';

export const isLang = (v: unknown): v is Lang => v === 'ar' || v === 'fr';
export const langOf = (v: unknown): Lang => (v === 'fr' ? 'fr' : 'ar');
export const dirOf = (l: Lang): 'rtl' | 'ltr' => (l === 'ar' ? 'rtl' : 'ltr');

/** يضيف بادئة اللغة للمسار الداخلي: ('fr','/products?x=1') → '/fr/products?x=1' ، ('fr','/') → '/fr/' */
export function localePath(lang: Lang, path: string): string {
  if (lang === 'ar' || !path.startsWith('/') || path.startsWith('//')) return path;
  if (path === '/') return '/fr/';
  if (/^\/fr(\/|$|\?|#)/.test(path)) return path;
  return '/fr' + path;
}

/** اللغة المستنتجة من مسار الصفحة */
export const langFromPath = (pathname: string): Lang => (/^\/fr(\/|$)/.test(pathname) ? 'fr' : 'ar');

/** مسار نفس الصفحة بلغة أخرى */
export function alternatePath(pathname: string, target: Lang): string {
  const base = pathname.replace(/^\/fr(?=\/|$)/, '') || '/';
  return localePath(target, base);
}

