export const dictionaries: Record<Lang, Dict> = { ar, fr };

/** ترجمة مفتاح مع استبدال {name}. مفتاح ناقص في لغة → يرجع للعربية → ثم للمفتاح نفسه */
export function t(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const raw = dictionaries[lang]?.[key] ?? ar[key] ?? key;
  return vars ? raw.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : raw;
}

/** «منتج واحد / منتجان / n منتجات» (أو الفرنسية) */
export function plural(lang: Lang, n: number): string {
  return t(lang, n === 1 ? 'plural.one' : n === 2 ? 'plural.two' : 'plural.many', { n });
}

/** يختار القيمة الفرنسية إن وُجدت وغير فارغة وإلا الأصلية (العربية) */
export function pick<T extends string | undefined | null>(lang: Lang, base: T, fr?: string | null): T | string {
  return lang === 'fr' && typeof fr === 'string' && fr.trim() ? fr : base;
}
